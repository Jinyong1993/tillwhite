<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;

class Role extends Model
{
    /**
     * Till White 시스템 역할
     *
     * Role은 사용자의 회사 직급(Position)이 아니라
     * 시스템에서 어떤 권한 묶음을 가지는지를 정의합니다.
     *
     * ------------------------------------------------------------
     * staff
     * ------------------------------------------------------------
     *
     * 일반 직원
     *
     * 기본적인 생산·폐기 기록 입력과 조회,
     * 자신의 근무·출퇴근·휴가 정보 확인,
     * 제품·레시피·매출 등의 조회 기능을 사용합니다.
     *
     * 실제 접근 가능한 데이터는
     * 사용자가 소속된 점포와 부서 범위로 제한됩니다.
     *
     * ------------------------------------------------------------
     * kitchen_head
     * ------------------------------------------------------------
     *
     * 주방 헤드 셰프
     *
     * 자신이 소속된 점포의 주방 부서를 기준으로
     * 생산, 근무 스케줄, 출퇴근, 휴가,
     * 제품, 레시피, 매출 등의 관리 기능을 사용합니다.
     *
     * 다른 점포 또는 홀 부서의 관리 권한을
     * 자동으로 가지는 것은 아닙니다.
     *
     * ------------------------------------------------------------
     * hall_manager
     * ------------------------------------------------------------
     *
     * 홀 매니저
     *
     * 자신이 소속된 점포의 홀 부서를 기준으로
     * 생산 관련 기록, 근무 스케줄, 출퇴근, 휴가,
     * 제품, 레시피, 매출 등의 관리 기능을 사용합니다.
     *
     * 다른 점포 또는 주방 부서의 관리 권한을
     * 자동으로 가지는 것은 아닙니다.
     *
     * ------------------------------------------------------------
     * head_office_staff
     * ------------------------------------------------------------
     *
     * 본사 직원
     *
     * 여러 점포의 생산, 제품, 레시피, 매출,
     * 직원 및 점포 정보 등을 조회할 수 있습니다.
     *
     * 본사 직원이라는 이유만으로
     * 점포 데이터를 수정할 수 있는 것은 아닙니다.
     *
     * ------------------------------------------------------------
     * head_office_manager
     * ------------------------------------------------------------
     *
     * 본사 관리자
     *
     * 전체 점포의 주요 정보를 조회할 수 있으며
     * 직원, 점포, 직급, 시스템 설정 등의
     * 관리 권한을 가질 수 있습니다.
     *
     * 본사 소속 직원의 근무 스케줄,
     * 출퇴근 및 휴가 관리에도 사용됩니다.
     *
     * 점포의 생산·제품·레시피·매출 데이터를
     * 무조건 수정할 수 있는 역할은 아닙니다.
     *
     * ------------------------------------------------------------
     * super_admin
     * ------------------------------------------------------------
     *
     * 최고 시스템 관리자
     *
     * 시스템에 등록된 모든 Permission을 가지며
     * 점포와 부서 범위의 제한 없이
     * 전체 시스템을 관리할 수 있습니다.
     *
     * 일반적인 본사 직원 또는 본사 관리자와는
     * 별도의 최고 관리자 역할입니다.
     *
     * ------------------------------------------------------------
     * Role / Position / Department / Permission 차이
     * ------------------------------------------------------------
     *
     * Role
     * - 시스템에서 어떤 권한 묶음을 가지는지 결정합니다.
     * - 예: staff, kitchen_head, head_office_manager
     *
     * Position
     * - 회사 조직상의 직급을 의미합니다.
     * - 예: 사원, 주임, 대리, 과장, 부장
     *
     * Department
     * - 사용자가 어느 조직 영역에 소속되어 있는지 나타냅니다.
     * - kitchen     : 주방
     * - hall        : 홀
     * - head_office : 본사
     *
     * Permission
     * - 실제 기능 단위의 세부 권한을 의미합니다.
     * - 예: production.view, schedule.manage, employee.manage
     *
     * 따라서 같은 Position을 가진 직원이라도
     * 서로 다른 Role을 가질 수 있습니다.
     */

    /**
     * 대량 할당 가능한 속성
     *
     * code        : 프로그램 내부에서 사용하는 역할 코드
     * name        : 화면에 표시할 역할명
     * description : 역할에 대한 상세 설명
     * is_active   : 역할 사용 여부
     */
    protected $fillable = [
        'code',
        'name',
        'description',
        'is_active',
    ];

    /**
     * 역할 컬럼의 타입 변환 설정
     *
     * is_active를 boolean 값으로 자동 변환합니다.
     */
    protected function casts(): array
    {
        return [
            'is_active' => 'boolean',
        ];
    }

    /**
     * 해당 역할을 사용하는 사용자 목록
     *
     * users.role_id를 기준으로
     * Role과 User를 일대다(One-to-Many) 관계로 연결합니다.
     *
     * 하나의 Role은 여러 User에게 부여될 수 있으며,
     * 현재 구조에서는 각 User가 하나의 Role을 가집니다.
     *
     * 예:
     * $role->users
     */
    public function users(): HasMany
    {
        return $this->hasMany(User::class);
    }

    /**
     * 역할에 부여된 권한 목록
     *
     * Role과 Permission은 role_permissions 테이블을 통해
     * 다대다(Many-to-Many) 관계를 가집니다.
     *
     * 하나의 Role은 여러 Permission을 가질 수 있고,
     * 하나의 Permission 역시 여러 Role에
     * 공통으로 부여될 수 있습니다.
     *
     * 예:
     * $role->permissions
     *
     * 위와 같이 사용하면 해당 역할에 부여된
     * 모든 기능 권한을 조회할 수 있습니다.
     *
     * 주의:
     * Permission은 "어떤 기능을 사용할 수 있는가"를 결정하고,
     * 실제 점포 및 부서의 데이터 접근 범위는
     * AccessService 및 Scope에서 별도로 제한합니다.
     */
    public function permissions(): BelongsToMany
    {
        return $this->belongsToMany(
            Permission::class,
            'role_permissions'
        );
    }
}