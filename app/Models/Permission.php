<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;

class Permission extends Model
{
    /**
     * Till White 시스템 권한
     *
     * 권한 코드는 "기능.행동" 형식으로 관리합니다.
     *
     * ------------------------------------------------------------
     * 생산·폐기 관리
     * ------------------------------------------------------------
     *
     * production.view
     * - 생산·폐기·로스 기록을 조회할 수 있는 권한
     * - 실제 조회 가능한 점포와 부서는 서버의 접근 범위에 따라 제한
     *
     * production.create
     * - 생산·폐기·로스 기록을 새로 등록할 수 있는 권한
     *
     * production.update
     * - 기존 생산·폐기·로스 기록을 수정할 수 있는 권한
     *
     * production.delete
     * - 기존 생산·폐기·로스 기록을 삭제할 수 있는 권한
     * - 실제 삭제는 Soft Delete 방식 사용
     *
     * ------------------------------------------------------------
     * 근무 스케줄 관리
     * ------------------------------------------------------------
     *
     * schedule.view
     * - 근무 스케줄을 조회할 수 있는 권한
     *
     * schedule.manage
     * - 근무 스케줄을 등록하거나 수정할 수 있는 권한
     * - 실제 관리 가능한 직원 범위는 점포 및 부서에 따라 제한
     *
     * ------------------------------------------------------------
     * 출퇴근 관리
     * ------------------------------------------------------------
     *
     * attendance.view
     * - 출근 및 퇴근 기록을 조회할 수 있는 권한
     *
     * attendance.manage
     * - 출퇴근 기록을 관리할 수 있는 권한
     * - 수동 수정 등의 관리 기능에 사용
     *
     * ------------------------------------------------------------
     * 휴가·희망휴무 관리
     * ------------------------------------------------------------
     *
     * leave.view
     * - 휴가 및 희망휴무 정보를 조회할 수 있는 권한
     * - 본인의 휴가 및 희망휴무 신청 기능에도 사용
     *
     * leave.manage
     * - 직원의 휴가 및 희망휴무 신청을 관리할 수 있는 권한
     * - 승인 및 반려 처리 등에 사용
     *
     * ------------------------------------------------------------
     * 제품 관리
     * ------------------------------------------------------------
     *
     * product.view
     * - 제품 및 제품 카테고리를 조회할 수 있는 권한
     *
     * product.manage
     * - 제품을 등록하거나 수정하고 사용 상태를 관리할 수 있는 권한
     *
     * ------------------------------------------------------------
     * 레시피 관리
     * ------------------------------------------------------------
     *
     * recipe.view
     * - 제품의 레시피를 조회할 수 있는 권한
     *
     * recipe.manage
     * - 레시피, 재료, 작업 순서 등을 등록하거나 관리할 수 있는 권한
     *
     * ------------------------------------------------------------
     * 매출 관리
     * ------------------------------------------------------------
     *
     * sales.view
     * - 매출 기록과 매출 상세 정보를 조회할 수 있는 권한
     *
     * sales.manage
     * - 매출을 등록하거나 관리할 수 있는 권한
     *
     * ------------------------------------------------------------
     * 직원 관리
     * ------------------------------------------------------------
     *
     * employee.view
     * - 직원 기본 정보와 소속 정보를 조회할 수 있는 권한
     *
     * employee.manage
     * - 직원을 등록하고 재직 상태 및 계정 상태 등을 관리할 수 있는 권한
     *
     * ------------------------------------------------------------
     * 점포 관리
     * ------------------------------------------------------------
     *
     * store.view
     * - 점포 정보를 조회할 수 있는 권한
     *
     * store.manage
     * - 점포를 등록하고 점포 정보를 관리할 수 있는 권한
     *
     * ------------------------------------------------------------
     * 직급 관리
     * ------------------------------------------------------------
     *
     * position.view
     * - 회사 직급 정보를 조회할 수 있는 권한
     *
     * position.manage
     * - 회사 직급 정보를 등록하거나 관리할 수 있는 권한
     *
     * ------------------------------------------------------------
     * 시스템 관리
     * ------------------------------------------------------------
     *
     * system.view
     * - 시스템 설정, 역할, 권한 등의 정보를 조회할 수 있는 권한
     *
     * system.manage
     * - 시스템 설정을 변경할 수 있는 권한
     * - 역할별 권한 설정 등의 관리 기능에 사용
     *
     * ------------------------------------------------------------
     * 감사 로그
     * ------------------------------------------------------------
     *
     * audit.view
     * - 시스템에서 발생한 감사 로그를 조회할 수 있는 권한
     * - 감사 로그는 일반 화면에서 수정하거나 삭제하지 않음
     *
     * ------------------------------------------------------------
     * 권한과 데이터 접근 범위
     * ------------------------------------------------------------
     *
     * Permission은 "어떤 기능을 사용할 수 있는가"를 결정합니다.
     *
     * 실제로 "어느 점포와 어느 부서의 데이터를 사용할 수 있는가"는
     * AccessService 및 각 Scope에서 별도로 제한합니다.
     *
     * 따라서 production.view 권한이 있다고 해서
     * 모든 점포의 생산 기록을 조회할 수 있다는 의미는 아닙니다.
     */

    /**
     * 대량 할당 가능한 속성
     *
     * code        : 프로그램 내부에서 사용하는 권한 코드
     * name        : 화면에 표시할 권한 이름
     * description : 권한에 대한 상세 설명
     * is_active   : 권한 사용 여부
     */
    protected $fillable = [
        'code',
        'name',
        'description',
        'is_active',
    ];

    /**
     * 권한 컬럼의 타입 변환 설정
     *
     * is_active를 boolean 값으로 자동 변환합니다.
     */
    protected function casts(): array
    {
        return [
            'is_active' => 'boolean',
        ];
    }

    /**
     * 해당 권한이 부여된 역할 목록
     *
     * 하나의 Permission은 여러 Role에 부여될 수 있고,
     * 하나의 Role 역시 여러 Permission을 가질 수 있습니다.
     *
     * 두 모델은 role_permissions 중간 테이블을 통해
     * 다대다(Many-to-Many) 관계를 가집니다.
     *
     * 예:
     * $permission->roles
     *
     * 위와 같이 사용하면 해당 권한이 부여된
     * 역할 목록을 조회할 수 있습니다.
     */
    public function roles(): BelongsToMany
    {
        return $this->belongsToMany(
            Role::class,
            'role_permissions'
        );
    }
}